# Writes docs/site/app-ads.txt from the real AdMob app ID.
#
#   powershell -ExecutionPolicy Bypass -File tools/write_app_ads_txt.ps1
#
# The publisher ID (pub-XXXXXXXXXXXXXXXX) is the part of the AdMob app ID before
# the "~". Google reads app-ads.txt from the developer website listed on the Play
# listing, so the file must be published at the site root:
#
#   https://quickben22.github.io/app-ads.txt
#
# Passing -Check only validates the inputs and prints the line without writing.
# Passing -AppId avoids reading local.properties (for CI, where the secret is an
# environment variable).
#
# A wrong publisher ID is worse than no file at all: Google treats a listed
# seller as authoritative, so the script refuses sample/test IDs.

param(
    [string]$AppId,
    [string]$OutputPath = (Join-Path $PSScriptRoot '..\docs\site\app-ads.txt'),
    [switch]$Check
)

$ErrorActionPreference = 'Stop'

function Get-LocalProperty {
    param([string]$Key)

    $file = Join-Path $PSScriptRoot '..\local.properties'
    if (-not (Test-Path $file)) { return $null }

    foreach ($line in Get-Content $file) {
        $trimmed = $line.Trim()
        if ($trimmed.StartsWith('#') -or -not $trimmed.Contains('=')) { continue }
        $name, $value = $trimmed.Split('=', 2)
        if ($name.Trim() -eq $Key) { return $value.Trim() }
    }
    return $null
}

if (-not $AppId) { $AppId = Get-LocalProperty 'admob.appId' }
if (-not $AppId -and $env:ADMOB_APP_ID) { $AppId = $env:ADMOB_APP_ID }
$AppId = "$AppId".Trim()

if (-not $AppId) {
    throw @'
No AdMob app ID found.

Set admob.appId in local.properties (gitignored):

    admob.appId=ca-app-pub-1234567890123456~1234567890

or pass -AppId or set ADMOB_APP_ID. Get the ID from AdMob > Apps > App settings.
'@
}

if ($AppId -notmatch '^(ca-app-pub-)(\d{16})~(\d{10})$') {
    throw "Not a valid AdMob app ID: '$AppId'. Expected ca-app-pub-<16 digits>~<10 digits>."
}

$publisherDigits = $Matches[2]
if ($publisherDigits -eq '3940256099942544') {
    throw 'That is Google''s sample publisher ID. Use the publisher ID from your own AdMob account.'
}

$line = "google.com, pub-$publisherDigits, DIRECT, f08c47fec0942fa0"

# If a banner unit is configured, its publisher must match the app's publisher.
# A mismatch means one of the two IDs belongs to a different AdMob account, and
# the banner would fail to serve in production.
$bannerId = Get-LocalProperty 'admob.bannerUnitId'
if (-not $bannerId -and $env:ADMOB_BANNER_UNIT_ID) { $bannerId = $env:ADMOB_BANNER_UNIT_ID }
$bannerId = "$bannerId".Trim()
if ($bannerId -and $bannerId -match '^ca-app-pub-(\d{16})/\d+$' -and $Matches[1] -ne $publisherDigits) {
    throw "Publisher mismatch: app ID uses pub-$publisherDigits but the banner uses pub-$($Matches[1])."
}

if ($Check) {
    "app-ads.txt line: $line"
    "target: $([IO.Path]::GetFullPath($OutputPath))"
    return
}

$target = [IO.Path]::GetFullPath($OutputPath)
$dir = Split-Path -Parent $target
New-Item -ItemType Directory -Force -Path $dir | Out-Null

$header = @(
    '# app-ads.txt for Prime or Not',
    '# Generated by tools/write_app_ads_txt.ps1 - edit the generator, not this file.',
    '# Served at https://quickben22.github.io/app-ads.txt',
    '# https://support.google.com/admob/answer/9363762',
    ''
)
Set-Content -Path $target -Value ($header + $line) -Encoding ascii

"wrote $target"
Get-Content $target | ForEach-Object { "  $_" }
